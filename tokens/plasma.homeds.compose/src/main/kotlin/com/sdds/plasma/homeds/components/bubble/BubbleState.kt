package com.sdds.plasma.homeds.components.bubble

/**
 * С какой стороны от триггера появляется тело бабла — терминология popover/tooltip (аналог
 * `side` у Radix/Floating UI), а не полный компас направлений: тело всегда растёт ОТ триггера
 * строго в одну из 4 сторон, а не по диагонали — диагональные варианты (напр. "сверху и с
 * выравниванием влево") задаются комбинацией [BubblePlacement] и [BubbleAlignment].
 *
 * [Start]/[End] зеркалируются под RTL (см. вызывающую сторону) — как и полагается сторонам,
 * заданным относительно направления текста, а не абсолютно "влево"/"вправо".
 *
 * По умолчанию сторону передаёт вызывающая сторона (например, на основе номера колонки карточки в
 * сетке) — но можно передать [Auto] и переложить выбор на компонент, см. его KDoc.
 */
public enum class BubblePlacement {

    /**
     * Тело бабла появляется НАД триггером (круг-якорь снизу).
     */
    Top,

    /**
     * Тело бабла появляется ПОД триггером (круг-якорь сверху).
     */
    Bottom,

    /**
     * Тело бабла появляется СБОКУ от триггера, со стороны начала (слева в LTR).
     */
    Start,

    /**
     * Тело бабла появляется СБОКУ от триггера, со стороны конца (справа в LTR).
     */
    End,

    /**
     * Автовыбор стороны по свободному месту в границах [BubbleHost] — компонент сам измеряет
     * расстояние от круга-якоря до всех 4 границ хоста и выбирает сторону с максимумом свободного
     * места (эвристика, не гарантия отсутствия наложения на границы хоста — тело растёт до своего
     * реального размера уже после выбора стороны, что-то вроде `flip`-мидлвара в popover-библиотеках).
     * В этом режиме [BubbleAlignment], переданный отдельным параметром, ИГНОРИРУЕТСЯ — он тоже
     * подбирается автоматически по той же логике (свободное место вдоль перпендикулярной оси).
     *
     * `Auto` — это стратегия выбора, а не сторона: значение никогда не доходит до геометрии/layout
     * компонента, [BubbleTrigger] разрешает его в конкретную сторону+выравнивание ДО передачи
     * дальше по системе.
     */
    Auto,
}

/**
 * Выравнивание тела бабла вдоль оси, ПЕРПЕНДИКУЛЯРНОЙ направлению роста ([BubblePlacement]) —
 * терминология popover/tooltip (аналог `align` у Radix/Floating UI). Для [BubblePlacement.Top]/
 * [BubblePlacement.Bottom] это горизонтальная ось (тело растёт вверх/вниз, выравнивание — влево/
 * вправо/по центру); для [BubblePlacement.Start]/[BubblePlacement.End] — вертикальная
 * (тело растёт вбок, выравнивание — вверх/вниз/по центру).
 *
 * [Start]/[End] на горизонтальной оси зеркалируются под RTL; на вертикальной оси RTL не влияет
 * (направление текста не меняет верх/низ).
 */
public enum class BubbleAlignment {

    /**
     * Тело выровнено по ближней (к началу оси) стороне круга-якоря — тот же угол тела, что и у
     * круга, остаётся ближним; шейка примыкает к углу тела, ближнему к кругу-якорю, и получает
     * уменьшенный радиус скругления (см. `BubbleDimensions.bodyNearCornerRadius`).
     */
    Start,

    /**
     * Тело центрировано относительно круга-якоря вдоль перпендикулярной оси — шейка примыкает к
     * середине ближнего края тела, оба соседних угла получают ОБЫЧНЫЙ (не уменьшенный) радиус:
     * ни один из них не является геометрически «ближним» к шейке однозначно.
     */
    Center,

    /**
     * Тело выровнено по дальней (от начала оси) стороне круга-якоря — зеркало [Start].
     */
    End,
}
